package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const (
	modulePath      = "github.com/hvritual/workspace"
	oldPrefix       = modulePath + "/gen/go"
	newPrefix       = modulePath + "/rpc/pb"
	generatedMarker = "// Code generated by dddgen. DO NOT EDIT."
)

var modules = []string{"workspace", "auth", "space", "system"}

func main() {
	root := flag.String("root", ".", "backend repository root")
	flag.Parse()

	replacements, err := rewriteTree(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("normalized dddgen pb imports: %d\n", replacements)
}

func rewriteTree(root string) (int, error) {
	total := 0
	for _, relativeRoot := range []string{"api", filepath.Join("internal", "modules")} {
		walkRoot := filepath.Join(root, relativeRoot)
		if _, err := os.Stat(walkRoot); err != nil {
			return 0, fmt.Errorf("stat %s: %w", walkRoot, err)
		}
		err := filepath.WalkDir(walkRoot, func(path string, entry fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if entry.IsDir() || (filepath.Ext(path) != ".go" && filepath.Ext(path) != ".proto") {
				return nil
			}

			data, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("read %s: %w", path, err)
			}
			occurrences := bytes.Count(data, []byte(oldPrefix))
			if occurrences == 0 {
				return nil
			}

			relativePath, err := filepath.Rel(root, path)
			if err != nil {
				return fmt.Errorf("resolve relative path for %s: %w", path, err)
			}
			if !allowedPath(relativePath, data) {
				return fmt.Errorf("refusing to rewrite old pb import in unrecognized file %s", relativePath)
			}

			updated := bytes.ReplaceAll(data, []byte(oldPrefix), []byte(newPrefix))
			info, err := entry.Info()
			if err != nil {
				return fmt.Errorf("stat %s: %w", path, err)
			}
			if err := writeAtomic(path, updated, info.Mode()); err != nil {
				return err
			}
			total += occurrences
			return nil
		})
		if err != nil {
			return 0, fmt.Errorf("rewrite %s: %w", walkRoot, err)
		}
	}
	return total, nil
}

func allowedPath(relativePath string, data []byte) bool {
	cleanPath := filepath.ToSlash(filepath.Clean(relativePath))
	if bytes.Contains(data, []byte(generatedMarker)) && strings.HasPrefix(cleanPath, "internal/modules/") {
		return true
	}

	for _, moduleName := range modules {
		allowed := []string{
			fmt.Sprintf("api/%s/v1/%s.proto", moduleName, moduleName),
			fmt.Sprintf("internal/modules/%s/module.go", moduleName),
			fmt.Sprintf("internal/modules/%s/internal/interfaces/grpc/client.go", moduleName),
			fmt.Sprintf("internal/modules/%s/internal/interfaces/proto/server.go", moduleName),
		}
		for _, candidate := range allowed {
			if cleanPath == candidate {
				return true
			}
		}
	}
	return false
}

func writeAtomic(path string, data []byte, mode fs.FileMode) (returnErr error) {
	temporary, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return fmt.Errorf("create temporary file for %s: %w", path, err)
	}
	temporaryPath := temporary.Name()
	defer func() {
		if err := os.Remove(temporaryPath); err != nil && !errors.Is(err, os.ErrNotExist) && returnErr == nil {
			returnErr = fmt.Errorf("remove temporary file %s: %w", temporaryPath, err)
		}
	}()

	if err := temporary.Chmod(mode.Perm()); err != nil {
		_ = temporary.Close()
		return fmt.Errorf("chmod temporary file for %s: %w", path, err)
	}
	if _, err := temporary.Write(data); err != nil {
		_ = temporary.Close()
		return fmt.Errorf("write temporary file for %s: %w", path, err)
	}
	if err := temporary.Sync(); err != nil {
		_ = temporary.Close()
		return fmt.Errorf("sync temporary file for %s: %w", path, err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close temporary file for %s: %w", path, err)
	}
	if err := os.Rename(temporaryPath, path); err != nil {
		return fmt.Errorf("replace %s: %w", path, err)
	}
	return nil
}
