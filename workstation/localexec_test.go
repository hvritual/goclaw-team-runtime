func TestLocalExecutorCreatesRevisionWorktreeAndSignedPatch(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("fake Codex shell fixture is POSIX-only")
	}
	requireGit(t)
	repository, baseCommit := createGitFixture(t)
	fakeCodex := writeExecutable(t, "fake-codex-success", `#!/bin/sh
printf '%s\n' '{"type":"thread.started","thread_id":"thread-local"}'
printf '%s\n' 'generated by fake codex' > generated.txt
printf '%s\n' '{"type":"turn.completed","usage":{"input_tokens":10,"output_tokens":5}}'
`)
	service, _ := newTestService(t, 2)
	key := testDeviceKey('l')
	registerTestRunner(t, service, "runner-local", key, []string{"alpha"}, []string{"codex", "go"})
	request := testEnqueueRequest("alpha", "local-success", "create generated.txt")
	request.ExecutionPack.RepositoryID = "fixture"
	request.ExecutionPack.BaseCommit = baseCommit
	request.ExecutionPack.AllowedPaths = []string{"generated.txt"}
	request.ExecutionPack.Verification = []CommandSpec{{
		Name: "generated file exists",
		Argv: []string{"/bin/sh", "-c", "test -f generated.txt"},
	}}
	task, err := service.Enqueue(request)
	if err != nil {
		t.Fatalf("Enqueue: %v", err)
	}
	claim := mustClaim(t, service, "runner-local", "alpha", "local-claim")
	executor, err := NewLocalExecutor(LocalExecConfig{
		RunnerID:               "runner-local",
		DeviceKeyPath:          filepath.Join(service.Config().Root, "credentials", "runner-local.key"),
		WorkRoot:               filepath.Join(t.TempDir(), "worktrees"),
		RepositoryPaths:        map[string]string{"fixture": repository},
		CodexCommand:           fakeCodex,
		TimeoutSeconds:         30,
		UnsafeHostVerification: true,
	})
	if err != nil {
		t.Fatalf("NewLocalExecutor: %v", err)
	}
	evidence, err := executor.ExecuteClaim(context.Background(), claim)
	if err != nil {
		t.Fatalf("ExecuteClaim: %v\nmetadata: %#v\nchecks: %#v", err, evidence.Metadata, evidence.Checks)
	}
	if evidence.Outcome != "completed" {
		t.Fatalf("outcome = %s", evidence.Outcome)
	}
	if err := VerifyEvidenceBundle(evidence, key); err != nil {
		t.Fatalf("VerifyEvidenceBundle: %v", err)
	}
	if evidence.DiffPatch == "" || !strings.Contains(evidence.DiffPatch, "generated by fake codex") {
		t.Fatalf("missing recoverable patch: %q", evidence.DiffPatch)
	}
	if evidence.DiffSHA256 != sha256Bytes([]byte(evidence.DiffPatch)) {
		t.Fatal("local diff digest mismatch")
	}
	if len(evidence.ChangedFiles) != 1 || evidence.ChangedFiles[0] != "generated.txt" {
		t.Fatalf("changed files = %#v", evidence.ChangedFiles)
	}
	if !strings.Contains(evidence.Metadata["worktree_relative"], "r1-a1") {
		t.Fatalf("worktree is not revision isolated: %s", evidence.Metadata["worktree_relative"])
	}
	if evidence.HeadCommit != baseCommit || evidence.CommitSHA != "" {
		t.Fatalf("executor committed changes: head=%s commit=%s", evidence.HeadCommit, evidence.CommitSHA)
	}
	if _, err := os.Stat(filepath.Join(repository, "generated.txt")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("base checkout was modified: %v", err)
	}
	completed, err := service.Complete(CompleteRequest{
		RunnerID: "runner-local", TaskID: task.ID, LeaseID: claim.Lease.ID,
		IdempotencyKey: "local-complete", Evidence: evidence,
	})
	if err != nil {
		t.Fatalf("Complete local evidence: %v", err)
	}
	if completed.Status != TaskCompleted {
		t.Fatalf("completed status = %s", completed.Status)
	}
	stored, err := service.GetEvidenceBundle(task.ID)
	if err != nil {
		t.Fatalf("GetEvidenceBundle: %v", err)
	}
	if stored.DiffPatch != evidence.DiffPatch {
		t.Fatal("stored local patch changed")
	}
}

func TestLocalExecutorReturnsSignedFailureForDeniedPath(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("fake Codex shell fixture is POSIX-only")
	}
	requireGit(t)
	repository, baseCommit := createGitFixture(t)
	fakeCodex := writeExecutable(t, "fake-codex-denied", `#!/bin/sh
printf '%s\n' '{"type":"thread.started","thread_id":"thread-denied"}'
printf '%s\n' 'must not change' > forbidden.txt
printf '%s\n' '{"type":"turn.completed","usage":{"input_tokens":10,"output_tokens":5}}'
`)
	service, _ := newTestService(t, 2)
	key := testDeviceKey('m')
	registerTestRunner(t, service, "runner-local", key, []string{"alpha"}, []string{"codex", "go"})
	request := testEnqueueRequest("alpha", "local-denied", "modify forbidden.txt")
	request.ExecutionPack.RepositoryID = "fixture"
	request.ExecutionPack.BaseCommit = baseCommit
	request.ExecutionPack.AllowedPaths = []string{"**"}
	request.ExecutionPack.DeniedPaths = []string{"forbidden.txt"}
	request.ExecutionPack.Verification = []CommandSpec{{
		Name: "fixture exists", Argv: []string{"/bin/sh", "-c", "test -f forbidden.txt"},
	}}
	task, err := service.Enqueue(request)
	if err != nil {
		t.Fatalf("Enqueue: %v", err)
	}
	claim := mustClaim(t, service, "runner-local", "alpha", "local-denied-claim")
	executor, err := NewLocalExecutor(LocalExecConfig{
		RunnerID:               "runner-local",
		DeviceKeyPath:          filepath.Join(service.Config().Root, "credentials", "runner-local.key"),
		WorkRoot:               filepath.Join(t.TempDir(), "worktrees"),
		RepositoryPaths:        map[string]string{"fixture": repository},
		CodexCommand:           fakeCodex,
		TimeoutSeconds:         30,
		UnsafeHostVerification: true,
	})
	if err != nil {
		t.Fatalf("NewLocalExecutor: %v", err)
	}
	evidence, executeErr := executor.ExecuteClaim(context.Background(), claim)
	if executeErr == nil {
		t.Fatal("denied path execution unexpectedly passed")
	}
	if evidence.Outcome != "failed" {
		t.Fatalf("failure outcome = %s", evidence.Outcome)
	}
	if err := VerifyEvidenceBundle(evidence, key); err != nil {
		t.Fatalf("signed failure did not verify: %v", err)
	}
	foundPolicyFailure := false
	for _, check := range evidence.Checks {
		if check.Name == "scope-policy" && !check.Passed &&
			strings.Contains(check.Details, "denied path changed") {
			foundPolicyFailure = true
		}
	}
	if !foundPolicyFailure {
		t.Fatalf("scope failure missing from evidence: %#v", evidence.Checks)
	}
	failed, err := service.Fail(FailRequest{
		RunnerID: "runner-local", TaskID: task.ID, LeaseID: claim.Lease.ID,
		IdempotencyKey: "local-fail", Error: executeErr.Error(), Evidence: &evidence,
	})
	if err != nil {
		t.Fatalf("Fail with signed evidence: %v", err)
	}
	if failed.Status != TaskFailed || failed.LastFailure == nil || failed.LastFailure.Evidence == nil {
		t.Fatalf("failed task = %#v", failed)
	}
}

func TestLocalExecutorEvidenceIncludesVerificationMutations(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("fake Codex shell fixture is POSIX-only")
	}
	requireGit(t)
	repository, baseCommit := createGitFixture(t)
	fakeCodex := writeExecutable(t, "fake-codex-verifier", `#!/bin/sh
printf '%s\n' '{"type":"thread.started","thread_id":"thread-verifier"}'
printf '%s\n' 'created by codex' > generated.txt
printf '%s\n' '{"type":"turn.completed","usage":{"input_tokens":10,"output_tokens":5}}'
`)
	service, _ := newTestService(t, 2)
	key := testDeviceKey('v')
	registerTestRunner(t, service, "runner-verifier", key, []string{"alpha"}, []string{"codex", "go"})
	request := testEnqueueRequest("alpha", "local-verifier", "create generated.txt")
	request.ExecutionPack.RepositoryID = "fixture"
	request.ExecutionPack.BaseCommit = baseCommit
	request.ExecutionPack.AllowedPaths = []string{"generated.txt"}
	request.ExecutionPack.Verification = []CommandSpec{{
		Name: "format generated file",
		Argv: []string{"/bin/sh", "-c", "printf '%s\\n' 'updated by verifier' > generated.txt"},
	}}
	if _, err := service.Enqueue(request); err != nil {
		t.Fatalf("Enqueue: %v", err)
	}
	claim := mustClaim(t, service, "runner-verifier", "alpha", "local-verifier-claim")
	executor, err := NewLocalExecutor(LocalExecConfig{
		RunnerID:               "runner-verifier",
		DeviceKeyPath:          filepath.Join(service.Config().Root, "credentials", "runner-verifier.key"),
		WorkRoot:               filepath.Join(t.TempDir(), "worktrees"),
		RepositoryPaths:        map[string]string{"fixture": repository},
		CodexCommand:           fakeCodex,
		TimeoutSeconds:         30,
		UnsafeHostVerification: true,
	})
	if err != nil {
		t.Fatalf("NewLocalExecutor: %v", err)
	}
	evidence, err := executor.ExecuteClaim(context.Background(), claim)
	if err != nil {
		t.Fatalf("ExecuteClaim: %v", err)
	}
	if !strings.Contains(evidence.DiffPatch, "updated by verifier") ||
		strings.Contains(evidence.DiffPatch, "created by codex") {
		t.Fatalf("signed patch does not reflect post-verification worktree: %q", evidence.DiffPatch)
	}
	if err := VerifyEvidenceBundle(evidence, key); err != nil {
		t.Fatalf("VerifyEvidenceBundle: %v", err)
	}
}

