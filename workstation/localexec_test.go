func requireGit(t *testing.T) {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not installed")
	}
}

func createGitFixture(t *testing.T) (string, string) {
	t.Helper()
	repository := filepath.Join(t.TempDir(), "repo")
	if err := os.MkdirAll(repository, 0o755); err != nil {
		t.Fatalf("MkdirAll repo: %v", err)
	}
	runGitFixture(t, repository, "init")
	runGitFixture(t, repository, "config", "user.name", "GoClaw Test")
	runGitFixture(t, repository, "config", "user.email", "goclaw@example.invalid")
	if err := os.WriteFile(filepath.Join(repository, "README.md"), []byte("# fixture\n"), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	runGitFixture(t, repository, "add", "README.md")
	runGitFixture(t, repository, "commit", "-m", "initial")
	return repository, strings.TrimSpace(runGitFixture(t, repository, "rev-parse", "HEAD"))
}

func runGitFixture(t *testing.T, repository string, args ...string) string {
	t.Helper()
	command := exec.Command("git", append([]string{"-C", repository}, args...)...)
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", args, err, output)
	}
	return string(output)
}

func writeExecutable(t *testing.T, name, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(content), 0o700); err != nil {
		t.Fatalf("write executable: %v", err)
	}
	return path
}
