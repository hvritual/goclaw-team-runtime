func TestSanitizedLocalEnvironmentProtectsControlPlaneSecrets(t *testing.T) {
	input := []string{
		"PATH=/usr/bin",
		"HOME=/home/alice",
		"GOCLAW_USER_TOKEN=user-secret",
		"GOCLAW_GATEWAY_TOKEN=gateway-secret",
		"GOCLAW_REVIEWER_TOKEN=test-only-reviewer",
		"GOCLAW_RUNNER_KEY_FILE=/run/secrets/runner.key",
		"GOCLAW_RUNNER_DEVICE_KEY=device-secret",
		"CODEX_ACCESS_TOKEN=test-only-codex-access",
		"CODEX_REFRESH_TOKEN=test-only-codex-refresh",
		"GOSKILLS_GATEWAY_WEBSOCKET_AUTH_TOKEN=legacy-secret",
		"GITHUB_TOKEN=github-secret",
		"NPM_TOKEN=npm-secret",
		"PUBLIC_VALUE=visible",
		"SSH_AUTH_SOCK=/run/user/1000/ssh-agent.socket",
		"DOCKER_HOST=unix:///run/docker.sock",
		"KUBECONFIG=/home/alice/.kube/config",
		"AWS_SHARED_CREDENTIALS_FILE=/home/alice/.aws/credentials",
		"LD_PRELOAD=/tmp/host-injection.so",
		"NODE_OPTIONS=--require=/tmp/host-injection.js",
	}
	got := sanitizedLocalEnvironment(
		input,
		[]string{
			"NPM_TOKEN",
			"GOCLAW_USER_TOKEN",
			"GOCLAW_REVIEWER_TOKEN",
			"CODEX_ACCESS_TOKEN",
			"CODEX_REFRESH_TOKEN",
			"PUBLIC_VALUE",
			"SSH_AUTH_SOCK",
			"LD_PRELOAD",
			"NODE_OPTIONS",
		},
	)
	joined := strings.Join(got, "\n")
	for _, expected := range []string{
		"PATH=/usr/bin",
		"NPM_TOKEN=npm-secret",
		"PUBLIC_VALUE=visible",
	} {
		if !strings.Contains(joined, expected) {
			t.Fatalf("expected %q in environment: %v", expected, got)
		}
	}
	for _, forbidden := range []string{
		"GOCLAW_USER_TOKEN",
		"GOCLAW_GATEWAY_TOKEN",
		"GOCLAW_REVIEWER_TOKEN",
		"GOCLAW_RUNNER_KEY_FILE",
		"GOCLAW_RUNNER_DEVICE_KEY",
		"CODEX_ACCESS_TOKEN",
		"CODEX_REFRESH_TOKEN",
		"GOSKILLS_GATEWAY_WEBSOCKET_AUTH_TOKEN",
		"GITHUB_TOKEN",
		"HOME=/home/alice",
		"SSH_AUTH_SOCK",
		"DOCKER_HOST",
		"KUBECONFIG",
		"AWS_SHARED_CREDENTIALS_FILE",
		"LD_PRELOAD",
		"NODE_OPTIONS",
	} {
		if strings.Contains(joined, forbidden) {
			t.Fatalf("protected %s leaked into environment: %v", forbidden, got)
		}
	}
}

